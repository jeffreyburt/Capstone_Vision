"""Render a synthetic test video of the two robots moving, with matching calibration files.

    python tools/make_sim_video.py
    python -m vision.main --config sim/config.yaml --show

Lets you exercise the whole pipeline (detection, geometry, tracking, output, debug view) on a laptop
with no camera, no printed markers and no robots. The simulated camera is 2 m high, like the real one.
"""

import argparse
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import cv2
import numpy as np
import yaml

from vision.config import load_config
from vision.geometry import CameraModel, FloorPose, Geometry
from vision.robots import robot_specs_from_config
from vision.sim import render_scene


def robot_poses(t):
    """Robot 1 drives a circle while spinning slowly; robot 2 strafes side to side, facing the camera-ish."""
    r1 = (1, -0.9 + 0.6 * math.cos(0.4 * t), 4.5 + 0.8 * math.sin(0.4 * t), (20 * t) % 360 - 180)
    r2 = (2, 1.0 + 0.8 * math.sin(0.5 * t), 3.5 + 1.5 * (0.5 + 0.5 * math.sin(0.15 * t)), -90 + 40 * math.sin(0.3 * t))
    return [r1, r2]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-dir", default="sim")
    ap.add_argument("--seconds", type=float, default=20)
    ap.add_argument("--fps", type=float, default=15)
    ap.add_argument("--size", default="1920x1080")
    args = ap.parse_args()

    cfg = load_config()
    specs = robot_specs_from_config(cfg)
    w, h = (int(v) for v in args.size.split("x"))
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    camera = CameraModel.from_fov(w, h, cfg["camera"].get("hfov_deg", 66))
    pose = FloorPose.look_at([0.0, 0.0, 2.0], [0.0, 4.5, 0.3])
    geom = Geometry(camera, pose)
    camera.save(out / "camera_intrinsics.yaml")
    pose.save(out / "floor_pose.yaml")

    # Config copy pointing at the sim calibration and video.
    sim_cfg = {k: v for k, v in cfg.items() if not k.startswith("_")}
    sim_cfg["camera"] = dict(cfg["camera"], source="sim.mp4")
    sim_cfg["calibration"] = {"intrinsics": "camera_intrinsics.yaml", "floor_pose": "floor_pose.yaml"}
    with open(out / "config.yaml", "w") as f:
        f.write("# Generated by tools/make_sim_video.py; paths are relative to this folder.\n")
        yaml.safe_dump(sim_cfg, f, sort_keys=False)

    writer = cv2.VideoWriter(str(out / "sim.mp4"), cv2.VideoWriter_fourcc(*"mp4v"), args.fps, (w, h))
    truth = []
    rng = np.random.default_rng(0)
    n = int(args.seconds * args.fps)
    for i in range(n):
        t = i / args.fps
        robots = robot_poses(t)
        writer.write(render_scene(geom, robots, specs, (w, h), cfg["markers"]["dictionary"], blur=0.8, noise=3, rng=rng))
        truth.append({"t": round(t, 3), "robots": [{"id": r[0], "x": round(r[1], 3), "y": round(r[2], 3),
                                                    "heading": round(r[3], 1)} for r in robots]})
        if i % 30 == 0:
            print(f"  frame {i}/{n}")
    writer.release()
    with open(out / "ground_truth.yaml", "w") as f:
        yaml.safe_dump(truth, f, sort_keys=False)
    print(f"Wrote {out / 'sim.mp4'}. Run:  python -m vision.main --config {out / 'config.yaml'} --show")


if __name__ == "__main__":
    main()
